"""Populate the database with clearly-labelled synthetic demo data.

Purpose: let someone see the dashboard and the Discord commands without waiting
for real discovery runs (and without hammering the public Roblox APIs).

Every row written here is explicitly marked:

* ``discovery_source`` is ``demo_seed``
* names are prefixed ``[DEMO]``
* descriptions start with ``[DEMO DATA]``
* notes and rejection reasons say so

The numbers are generated from a simple curve so that growth, scoring, charts
and the alert engine all exercise *real* code paths - but they are invented.
Never point this at a production database by accident: ``seed_demo`` refuses to
run when the configured database looks like a real deployment unless you pass
``force=True``.
"""

