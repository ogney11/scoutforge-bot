async def seed_demo(
    settings: Settings | None = None, *, force: bool = False, seed: int = 1337
) -> int:
    """Insert demo games, snapshots, scores, alerts and CRM history.

    Args:
        settings: Configuration to use (defaults to the process settings).
        force: Allow seeding a database that looks like production.
        seed: RNG seed so repeated runs produce identical data.

    Returns:
        Number of games seeded.
    """
    settings = settings or get_settings()
    _guard(settings, force=force)

    # S311: reproducible demo fixtures need stable pseudo-randomness, not secrets.
    rng = random.Random(seed)  # noqa: S311
    now = utcnow()
    engine = create_engine(settings.database)
    factory = create_session_factory(engine)
    scorer = ScoutScorer(weights=settings.score, alerts=settings.alerts)
    alert_engine = AlertEngine(settings.alerts)
    lead_min_score = settings.alerts.lead_min_score
    warm_threshold = settings.alerts.warm_score

    seeded = 0
    try:
        async with factory() as session:
            games_repo = GameRepository(session)
            snapshots_repo = GameSnapshotRepository(session)
            scores_repo = GameScoreRepository(session)
            alerts_repo = AlertRepository(session)
            runs_repo = DiscoveryRunRepository(session)
            scouts_repo = ScoutUserRepository(session)
            leads = LeadService(session)

            for scout in DEMO_SCOUTS:
                await scouts_repo.upsert(
                    scout["discord_id"],
                    display_name=scout["display_name"],
                    is_admin=scout["is_admin"],
                )

            for spec in DEMO_GAMES:
                if await games_repo.get(spec["universe_id"]) is not None:
                    continue
                seeded += 1
                await _seed_game(
                    spec,
                    now=now,
                    rng=rng,
                    games=games_repo,
                    snapshots=snapshots_repo,
                    scores=scores_repo,
                    alerts=alerts_repo,
                    leads=leads,
                    scorer=scorer,
                    alert_engine=alert_engine,
                    lead_min_score=lead_min_score,
                    warm_threshold=warm_threshold,
                )

            await _seed_history(runs=runs_repo, now=now, rng=rng, seeded=seeded)
            await session.commit()
    finally:
        await engine.dispose()

    log_event(log, 20, "DEMO_SEEDED", games=seeded)
    return seeded


async def _seed_game(
    spec: dict[str, Any],
    *,
    now: Any,
    rng: random.Random,
    games: GameRepository,
    snapshots: GameSnapshotRepository,
    scores: GameScoreRepository,
    alerts: AlertRepository,
    leads: LeadService,
    scorer: ScoutScorer,
    alert_engine: AlertEngine,
    lead_min_score: float,
    warm_threshold: float,
) -> None:
    universe_id = spec["universe_id"]
    age_hours = spec["age_hours"]
    first_seen = now - timedelta(hours=age_hours)
    series = _build_series(spec, now=now, rng=rng)

    latest = series[-1]
    result = await games.upsert(
        universe_id,
        {
            "game_name": DEMO_PREFIX + spec["name"],
            "description": DEMO_BANNER,
            "creator_id": None,
            "creator_name": spec["creator"],
            "creator_type": spec["creator_type"],
            "current_ccu": latest["current_ccu"],
            "lifetime_visits": latest["lifetime_visits"],
            "favorites": latest["favorites"],
            "likes": latest["likes"],
            "dislikes": latest["dislikes"],
            "peak_ccu": max(p["current_ccu"] for p in series),
            "roblox_url": f"https://www.roblox.com/games/{universe_id}",
            "public_discord_url": None,
            "missing_metrics": ["playing_now", "voice_chat_visits"],
        },
        source=DEMO_SOURCE,
    )
    game = result.game
    # upsert() stamps first_seen_at with now(); the demo history predates that.
    game.first_seen_at = first_seen

    await snapshots.add_many([{**point, "source": DEMO_SOURCE} for point in series])
    stored = await snapshots.window(universe_id, limit=HOURS_OF_HISTORY)

    # Score at points inside the observed window so the score chart is a real
    # series - and so no score claims to know more than was observed at the time.
    span_start = _utc(series[0]["captured_at"])
    span_end = _utc(series[-1]["captured_at"])
    final = None
    for fraction in (0.0, 0.33, 0.66, 1.0):
        at = span_start + (span_end - span_start) * fraction
        point = _nearest(series, at)
        earlier = [p for p in stored if _utc(p.captured_at) <= at]
        partial = compute_growth(universe_id, earlier, now=at)
        score = scorer.score(
            ScoreInput(
                universe_id=universe_id,
                name=game.game_name,
                current_ccu=point["current_ccu"],
                lifetime_visits=point["lifetime_visits"],
                favorites=point["favorites"],
                likes=point["likes"],
                dislikes=point["dislikes"],
                first_seen_at=first_seen,
                peak_ccu=max(p["current_ccu"] for p in series if _utc(p["captured_at"]) <= at),
                snapshot_count=len(earlier),
                growth=partial,
                now=at,
            ),
            now=at,
        )
        row = score.to_row()
        row["computed_at"] = at
        await scores.add(row)
        final = score

    assert final is not None  # the loop above always runs at least once
    await games.set_score(game, score=final.score, level=final.level)
    await games.mark_lead(game, lead_min_score=lead_min_score)

    if final.score >= warm_threshold:
        await _seed_alerts(
            universe_id,
            stored=stored,
            final=final,
            alerts=alerts,
            engine=alert_engine,
        )

    for author_id, body in DEMO_NOTES.get(universe_id, []):
        await leads.add_note(universe_id, body, author_id=author_id, author_name="demo_scout")

    pipeline = DEMO_PIPELINES.get(universe_id)
    if pipeline:
        for status in pipeline:
            try:
                await leads.change_status(
                    universe_id,
                    status,
                    actor_id=1_000_000_001,
                    actor_name="demo_scout",
                    reason="[DEMO DATA] seeded pipeline state",
                )
            except ValueError:
                continue


async def _seed_alerts(
    universe_id: int,
    *,
    stored: list[Any],
    final: Any,
    alerts: AlertRepository,
    engine: AlertEngine,
) -> None:
    """Replay the alert engine over recent snapshots to create real decisions.

    The engine is driven with the same snapshots the scorer saw, so the stored
    decisions are reproducible rather than hand-written.
    """
    ordered = sorted(stored, key=lambda s: _utc(s.captured_at))
    recent = ordered[-4:]
    if not recent:
        return
    first_index = ordered.index(recent[0])

    previous_alert: LastAlertState | None = None
    previous_score: float | None = None
    for offset, point in enumerate(recent):
        history = ordered[max(0, first_index + offset - 12) : first_index + offset + 1]
        growth = compute_growth(universe_id, history, now=_utc(point.captured_at))
        # Walk the score up to the real current value so the newest evaluation
        # uses ``final.score`` exactly. The small step keeps two evaluations
        # inside the HOT cooldown, which demonstrates suppression.
        score_value = round(min(100.0, max(0.0, final.score - (len(recent) - 1 - offset) * 1.5)), 2)
        decision = engine.evaluate(
            score=score_value,
            growth=growth,
            last_alert=previous_alert,
            current_ccu=point.current_ccu,
            now=_utc(point.captured_at),
        )
        if decision.level in (AlertLevel.HOT, AlertLevel.EXTREME):
            delivered = decision.should_notify
            await alerts.add(
                {
                    "universe_id": universe_id,
                    "level": decision.level.value,
                    "score": score_value,
                    "previous_score": previous_score,
                    "score_delta": decision.score_delta,
                    "ccu": point.current_ccu,
                    "ccu_spike_pct": decision.ccu_spike_pct,
                    "delivered": delivered,
                    "suppressed_reason": None if delivered else decision.reason,
                    "created_at": _utc(point.captured_at),
                }
            )
            if delivered:
                previous_alert = LastAlertState(
                    created_at=_utc(point.captured_at),
                    level=decision.level,
                    score=score_value,
                    ccu=point.current_ccu,
                )
        previous_score = score_value


async def _seed_history(
    *, runs: DiscoveryRunRepository, now: Any, rng: random.Random, seeded: int
) -> None:
    """Create a plausible trail of past discovery runs."""
    if seeded == 0:
        return
    for hours_ago in range(HOURS_OF_HISTORY // 6, 0, -1):
        candidates = rng.randint(35, 140)
        accepted = rng.randint(0, max(1, candidates // 8))
        run = await runs.start(triggered_by="scheduler")
        run.started_at = now - timedelta(hours=hours_ago)
        run.candidates_found = candidates
        run.candidates_processed = candidates
        run.games_discovered = accepted
        run.games_accepted = accepted
        run.games_rejected = candidates - accepted
        run.snapshots_written = accepted
        run.alerts_sent = rng.randint(0, 2)
        run.rejection_reasons = {
            "ccu_below_minimum": max(0, candidates - accepted - 4),
            "lifetime_visits_too_high": rng.randint(0, 5),
        }
        run.source_stats = {"roblox_explore": candidates // 2, "roblox_search": candidates // 3}
        await runs.finish(run, status=RunStatus.SUCCESS)
        # finish() stamps "now"; move the run back onto its own timeline.
        run.finished_at = run.started_at + timedelta(seconds=rng.uniform(1.8, 9.0))
        run.duration_ms = int((run.finished_at - run.started_at).total_seconds() * 1000)


def _utc(value: datetime | None) -> datetime:
    """Strict :func:`ensure_utc` - demo fixtures must always carry a timestamp."""
    result = ensure_utc(value)
    if result is None:  # pragma: no cover - fixtures are built with timestamps
        raise ValueError("demo fixture row is missing a timestamp")
    return result


def _build_series(spec: dict[str, Any], *, now: Any, rng: random.Random) -> list[dict[str, Any]]:
    """Generate a metric series that ends at the spec's current values.

    The series is built *backwards* from ``end_ccu`` so the newest point is the
    value the dashboard and the filters will read, while older points follow the
    spec's growth rate. ``end_visits`` is set explicitly because the lifetime
    footprint component is what separates a genuinely new game from an old one
    wearing a CCU spike.
    """
    end_ccu = spec["end_ccu"]
    end_visits = spec["end_visits"]
    curve = spec["curve"]
    growth = spec["growth"]
    favourite_ratio = rng.uniform(0.02, 0.05)
    like_ratio = rng.uniform(0.12, 0.24)
    dislike_ratio = rng.uniform(0.01, 0.03)

    points: list[dict[str, Any]] = []
    # Never fabricate history for longer than the game has existed: the series
    # starts when ScoutForge would first have seen it.
    span_hours = min(HOURS_OF_HISTORY, int(spec["age_hours"]))
    for step in range(span_hours, -1, -SAMPLE_EVERY_HOURS):
        hours_ago = step
        if curve == "flat":
            drift = 1.0 + 0.05 * math.sin(step / 6.0)
        elif growth >= 0:
            drift = (1.0 + growth) ** (-hours_ago / 24.0)
        else:
            drift = 1.0 / (1.0 + abs(growth)) ** (hours_ago / 24.0)
        noise = 1.0 + rng.uniform(-0.03, 0.03)
        ccu = max(20, int(end_ccu * drift * noise))

        # Visits accumulate monotonically towards end_visits.
        progress = 1.0 - (hours_ago / span_hours) if span_hours else 1.0
        visits = max(
            1, int(end_visits * (0.28 + 0.72 * progress) * (1.0 + rng.uniform(-0.01, 0.01)))
        )
        points.append(
            {
                "universe_id": spec["universe_id"],
                "captured_at": now - timedelta(hours=hours_ago),
                "current_ccu": ccu,
                "lifetime_visits": visits,
                "favorites": max(0, int(visits * favourite_ratio)),
                "likes": max(0, int(visits * like_ratio)),
                "dislikes": max(0, int(visits * dislike_ratio)),
            }
        )
    return points


def _nearest(series: list[dict[str, Any]], at: Any) -> dict[str, Any]:
    target = _utc(at)
    return min(series, key=lambda p: abs((_utc(p["captured_at"]) - target).total_seconds()))


#: Host fragments that mean "this is not a scratch database". ``mysql`` and
#: ``scoutforge-db`` are the compose service names from ``docker-compose.yml``;
#: a sqlite scratch file lives on ``localhost``/``127.0.0.1`` and is unaffected.
_PRODUCTION_HOST_TOKENS = ("prod", "postgres", "scoutforge", "mysql", "db-primary")

_REFUSAL = (
    "Refusing to seed demo data into what looks like a production database. "
    "Re-run with force=True (scoutforge/scripts/seed_demo.py) if that is really intended."
)


def _guard(settings: Settings, *, force: bool) -> None:
    """Refuse to litter what looks like a production database.

    Matching is deliberately limited to the database *host*. Substring matching
    the whole URL also fires on innocent local paths - a scratch directory called
    ``/tmp/test_production/`` would be refused - which trains people to reach for
    ``force=True`` until it stops meaning anything.
    """
    if force:
        return
    if settings.is_production:
        raise RuntimeError(_REFUSAL)
    host = (urlsplit(settings.database.database_url).hostname or "").lower()
    if any(token in host for token in _PRODUCTION_HOST_TOKENS):
        raise RuntimeError(_REFUSAL)


